#!/usr/bin/env python3
"""tab_offgpu_peak -- per TPC-H query at SF1000, the peak intermediate data
each GPU engine holds outside GPU memory at once: every engine has to put
intermediates off the GPU on the same heavy queries.

    python3 make_offgpu_table.py --pf-raw JSONL [JSONL ...]
        --pf-adaptive JSONL --sirius-split JSON [--spill CSV]
        -> experiments/paper_scripts/results/tab_offgpu_peak.tex

Per engine (GB, decimal):
  PageFlow     the pinned host pool's peak of intermediate blocks
               (``peak_host_intermediate``) minus the GPU cache region
               (``--cache-gb``, 20 GiB): a lower bound on the live
               intermediates that cannot be on the GPU (every region has a
               home in host memory, so at most the cache's worth of them is
               also on the GPU).  RAW, and adaptive compression (bytes as
               stored, compressed)
  Sirius       the peak of intermediate batches resident in its host tier
               (the quent traces; scan batches left out): ``--sirius-split``
  cudf-Polars  the rapidsmpf pinned host pool's peak (the spill target; a
               process lifetime peak, its SF1 warm pass included)
  Spark-RAPIDS the larger of two sampled peaks, the shuffle and spill files
               under spark.local.dir and the host spill store (a lower bound
               on the data held at once); mostly shuffle files, written by
               design

A query an engine did not complete in its spill pass shows the peak it had
reached, as a lower bound, with the failure (T/O, Disk, FAIL).
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.join(os.path.dirname(HERE), "results")
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "helpers"))
import spill_profile  # noqa: E402

SPILL_CSV = os.environ.get("TQP_SPILL_CSV") or os.path.normpath(os.path.join(
    HERE, os.pardir, os.pardir, os.pardir, "baselines", "results", "spill_profile.csv"))
QUERIES = list(range(1, 23))
GB = 1e9
WORD = {"TIMEOUT": "T/O", "KILLED_DISK": "Disk", "FAIL": "FAIL"}


def load_pf(files):
    out = {}
    for path in files:
        with open(path, encoding="utf-8") as f:
            for line in f:
                r = json.loads(line)
                q = int(r["query"].removeprefix("query"))
                rows = {x["kind"]: x for x in r["rows"]}
                out[q] = (r["run_status"], rows["peak_host_intermediate"]["logical_b"])
    return out


def cell(v, status="OK"):
    """A table cell: GB rounded, '0' below 0.5 GB; a failure as a lower bound."""
    s = "0" if v < 0.5 * GB else f"{v / GB:.0f}"
    if status != "OK":
        word = WORD.get(status, "FAIL")
        return word if s == "0" else f"$\\geq${s} ({word})"
    return s


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--pf-raw", nargs="+", required=True)
    ap.add_argument("--pf-adaptive", nargs="+", required=True)
    ap.add_argument("--sirius-split", required=True)
    ap.add_argument("--spill", default=SPILL_CSV)
    ap.add_argument("--cache-gb", type=float, default=20 * 2**30 / GB)
    ap.add_argument("--min-gb", type=float, default=1.0,
                    help="rows: the queries where some engine holds at least this much")
    ap.add_argument("--out", default=os.path.join(RESULTS, "tab_offgpu_peak.tex"))
    ap.add_argument("--summary", default=os.path.join(RESULTS, "tab_offgpu_peak_summary.tex"),
                    help="the 4-row table: each engine's largest peak over the queries it completed")
    args = ap.parse_args()

    cells = spill_profile.load(args.spill)
    raw, adp = load_pf(args.pf_raw), load_pf(args.pf_adaptive)
    with open(args.sirius_split, encoding="utf-8") as f:
        sir = json.load(f)
    cache = args.cache_gb * GB

    def base(key, q, kinds):
        # Peaks sampled apart: the largest of them is still a lower bound on
        # the data held at once (their sum need not be).
        c = cells[(key, 1000)][q]
        return max(c["rows"][k]["logical_b"] or 0 for k in kinds), c["run_status"]

    table = {}
    for q in QUERIES:
        table[q] = {
            "raw": (max(0, raw[q][1] - cache), raw[q][0]),
            "adp": (max(0, adp[q][1] - cache), adp[q][0]),
            "sirius": (sir[str(q)].get("peak_host_intermediate_b", 0),
                       cells[("sirius", 1000)][q]["run_status"]),
            "polars": base("polars_gpu", q, ("peak_host",)),
            "rapids": base("rapids", q, ("peak_disk", "peak_host")),
        }
    cols = ["raw", "adp", "sirius", "polars", "rapids"]
    rows = [q for q in QUERIES if any(table[q][c][0] >= args.min_gb * GB for c in cols)]

    lines = [
        "% Generated by experiments/paper_scripts/figures/make_offgpu_table.py; do not edit.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Peak intermediate data held outside GPU memory at once (GB) on TPC-H at SF1000, "
        "per query.  Every engine has to place intermediates off the GPU on the heavy queries.}",
        "\\label{tab:offgpu-peak}",
        "\\small",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{@{}lrrrrr@{}}",
        "\\toprule",
        " & \\multicolumn{2}{c}{PageFlow} & & & \\\\",
        "\\cmidrule(lr){2-3}",
        "Query & RAW & Adaptive & Sirius & cudf-Polars & Spark-RAPIDS \\\\",
        "\\midrule",
    ]
    for q in rows:
        lines.append(f"Q{q} & " + " & ".join(cell(*table[q][c]) for c in cols) + " \\\\")
    lines.append("\\midrule")
    n = {c: sum(1 for q in QUERIES if table[q][c][0] >= args.min_gb * GB) for c in cols}
    lines.append(f"Queries $\\geq$\\,{args.min_gb:g}\\,GB & "
                 + " & ".join(f"{n[c]}/22" for c in cols) + " \\\\")
    top = {c: max(QUERIES, key=lambda q: table[q][c][0]) for c in cols}
    lines.append("Largest & " + " & ".join(
        f"{table[top[c]][c][0] / GB:.0f} (Q{top[c]})" for c in cols) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    for path in (args.out, args.summary):
        os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("\n".join(lines))
    print(f"  wrote {args.out}")

    def peak(c):
        ok = [q for q in QUERIES if table[q][c][1] == "OK"]
        q = max(ok, key=lambda q: table[q][c][0])
        return table[q][c][0] / GB, q
    held = {"adp": "host memory (compressed)", "sirius": "host tier",
            "polars": "pinned host pool", "rapids": "disk (shuffle files)"}
    names = {"adp": "PageFlow", "sirius": "Sirius", "polars": "cudf-Polars",
             "rapids": "Spark-RAPIDS"}
    rv, rq = peak("raw")
    summ = [
        "% Generated by experiments/paper_scripts/figures/make_offgpu_table.py; do not edit.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Each engine's largest peak of intermediate data held outside GPU memory "
        "at once on TPC-H at SF1000 (GB), over the queries it completed.}",
        "\\label{tab:offgpu-peak-summary}",
        "\\small",
        "\\begin{tabular}{@{}lrcl@{}}",
        "\\toprule",
        "Engine & Peak (GB) & Query & Held in \\\\",
        "\\midrule",
    ]
    for c in ("adp", "sirius", "polars", "rapids"):
        v, q = peak(c)
        extra = f" (RAW: {rv:.0f})" if c == "adp" and rq == q else (f" (RAW: {rv:.0f}, Q{rq})" if c == "adp" else "")
        summ.append(f"{names[c]} & {v:.0f}{extra} & Q{q} & {held[c]} \\\\")
    summ += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    with open(args.summary, "w", encoding="utf-8") as f:
        f.write("\n".join(summ))
    print("\n".join(summ))
    print(f"  wrote {args.summary}")


if __name__ == "__main__":
    main()
